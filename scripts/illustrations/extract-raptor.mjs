/**
 * Extracts engine pieces from the pre-built raptor-engine.html,
 * groups them into animation assemblies, and writes rocket-explode-markup.ts.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as k from "../anatomy/kit/iso-kit.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "../..");

const html = readFileSync(join(HERE, "../anatomy/examples/raptor-engine/raptor-engine.html"), "utf8");

// ── Extract front SVG (the engine items) ──────────────────────────────────
const svgs = html.match(/<svg[^>]*class="iso-svg[^"]*"[^>]*>[\s\S]*?<\/svg>/g);
const frontSvg = svgs[1]; // rp-front
const engineContent = frontSvg.match(/<g class="rp-engine">([\s\S]*)<\/g><\/svg>/)?.[1] ?? "";

// ── Animation assembly grouping ────────────────────────────────────────────
// We animate 4 groups that explode apart:
//   gimbal   — top (moves most upward)
//   ftp      — turbopump side assembly (moves up + out)
//   chamber  — main chamber + preburner + OTP (moves up)
//   nozzle   — bell nozzle (stays / moves down)
const ASM_BY_PIECE = {
  gimbal:    "gimbal",
  otp:       "chamber",
  orpb:      "chamber",
  chamber:   "chamber",
  ftp:       "ftp",
  hotgas:    "ftp",
  lox:       "ftp",
  downcomer: "ftp",
  nozzle:    "nozzle",
};

// Draw the nozzle behind the chamber so its rim cannot hide the assembled joint.
const groups = { nozzle: "", gimbal: "", chamber: "", ftp: "" };

// Each item is: <g class="it" data-piece="..." data-k="..." data-m="..." data-i="...">...</g>
// Items are sorted by painter's key (data-k) in the HTML already.
// Preserve the card's existing shape fragments and wrapper attributes.
// Close each fragment's nested groups so later assemblies cannot inherit its motion.
const itemRex = /<g class="it" data-piece="([^"]+)"[^>]*>([\s\S]*?)<\/g>/g;
let m;
while ((m = itemRex.exec(engineContent)) !== null) {
  const asm = ASM_BY_PIECE[m[1]];
  if (!asm) continue;
  const fragment = m[0];
  const openGroups = [...fragment.matchAll(/<g\b[^>]*>/g)].length;
  const closedGroups = [...fragment.matchAll(/<\/g>/g)].length;
  groups[asm] += fragment + "</g>".repeat(openGroups - closedGroups);
}

for (const [asm, svg] of Object.entries(groups)) {
  console.log(`${asm}: ${svg.length} chars`);
}

// ── ViewBox: nozzle fixed, upper parts rise by up to 100 * 1.2539 ≈ 125 SVG px ─
// Assembled bbox: x 363–584, y 90–537
// Gimbal rises 125px up: y min = 90 - 125 = -35
// Nozzle stays: y max = 537
// Union + 22px padding: x=341 y=-57 w=265 h=616
const CARD_VB = "341 -57 265 616";

const HERO_WIDTH = 616 * 720 / 570;
const HERO_VB = `${550 - HERO_WIDTH / 2} -57 ${HERO_WIDTH} 616`;
const LABEL_X = 646;
const CALLOUTS = {
  gimbal: { at: [502.8, 110], title: "Gimbal", sub: "direction & intent" },
  ftp: { at: [584.2, 215], title: "Turbopump", sub: "JSON & data" },
  chamber: { at: [504, 305], title: "Chamber", sub: "code & logic" },
  nozzle: { at: [557.4, 465], title: "Nozzle", sub: "APIs & output" },
};
const callouts = Object.fromEntries(Object.entries(CALLOUTS).map(([name, { at: [x, y], title, sub }]) => [
  name,
  `<g class="co"><circle class="co-dot" cx="${x}" cy="${y}" r="1.8"/><path class="co-line" d="M${x} ${y}H${LABEL_X - 6}" fill="none"/><text class="co-title" x="${LABEL_X}" y="${y - 1}">${title}</text><text class="co-sub" x="${LABEL_X}" y="${y + 11}">${sub.replaceAll("&", "&amp;")}</text></g>`,
]));

// ── ROCKET_UP: world-Z unit vector in SVG space ────────────────────────────
// Raptor build uses azimuth=38, elevation=27, fitProjection over stand+engine bbox.
// We reconstruct P with the same bounding points from build.mjs.
const Z_EXIT = 172, TOP = 310, BEAM_Z = Z_EXIT + TOP + 23, BEAM_H = 28;
const COLUMN_AT = [[-124, 124], [124, -124]];
const COLUMN = 24;
const DECK = { x: -150, y: -150, w: 300, d: 300, r: 10 };
const DECK_H = 15, FOOT_H = 8;

const P = k.fitProjection(
  [
    ...k.boxCorners(DECK, -DECK_H - FOOT_H, 0),
    [COLUMN_AT[0][0] - COLUMN, COLUMN_AT[0][1] + COLUMN, BEAM_Z + BEAM_H],
    [COLUMN_AT[1][0] + COLUMN, COLUMN_AT[1][1] - COLUMN, BEAM_Z + BEAM_H],
    [-190 / Math.SQRT2,  190 / Math.SQRT2, BEAM_Z + BEAM_H],
    [ 190 / Math.SQRT2, -190 / Math.SQRT2, BEAM_Z + BEAM_H],
  ],
  932, 900,
  { pad: 26, azimuth: 38, elevation: 27 }
);

const ez = k.axisVector(P, [0, 0, 1]);
console.log("ROCKET_UP:", ez);

// ── Write TypeScript output ────────────────────────────────────────────────
const ts = `// Auto-generated by scripts/illustrations/extract-raptor.mjs — do not edit by hand.

/** World-Z unit vector in SVG space (matches raptor-engine projection). */
export const ROCKET_UP: [number, number] = [${ez[0].toFixed(4)}, ${ez[1].toFixed(4)}];

const ASSEMBLIES: Record<string, string> = ${JSON.stringify(groups)};
const CALLOUTS: Record<string, string> = ${JSON.stringify(callouts)};

function renderRocket(viewBox: string, callouts: boolean) {
  const parts = Object.entries(ASSEMBLIES).map(([name, content]) => '<g data-asm="' + name + '">' + content + (callouts ? CALLOUTS[name] : '') + '</g>').join('');
  return '<svg xmlns="http://www.w3.org/2000/svg" class="iso-svg" viewBox="' + viewBox + '" role="img" aria-label="An exploded Raptor-style rocket engine: nozzle bell, combustion chamber, turbopump assembly and gimbal.">' + parts + '</svg>';
}

export const ROCKET_CARD_SVG = renderRocket(${JSON.stringify(CARD_VB)}, false);
export const ROCKET_EXPLODE_SVG = renderRocket(${JSON.stringify(HERO_VB)}, true);
`;

writeFileSync(join(ROOT, "src/components/illustrations/rocket-explode-markup.ts"), ts, "utf8");
console.log("Written rocket-explode-markup.ts", (ts.length / 1024).toFixed(0), "KB");
